function glyphBytes(idx: number): Uint8Array {
  if (idx >= EXTRA_FIRST && idx < EXTRA_FIRST + EXTRA_6X8.length / GLYPH_WIDTH) {
    const off = (idx - EXTRA_FIRST) * GLYPH_WIDTH;
    return EXTRA_6X8.subarray(off, off + GLYPH_WIDTH);
  }
  const clampedIdx = idx >= FIRST_CHAR && idx < FIRST_CHAR + CHAR_COUNT ? idx : FIRST_CHAR;
  const off = (clampedIdx - FIRST_CHAR) * GLYPH_WIDTH;
  return DATA_6X8.subarray(off, off + GLYPH_WIDTH);
}

// Decode one UTF-8 character from a string starting at position `pos`.
// Returns [glyphIndex, charsConsumed].
function decodeUtf8Char(str: string, pos: number): [number, number] {
  const c0 = str.charCodeAt(pos);

  // Handle JS surrogate pairs (emoji etc.) — render as space
  if (c0 >= 0xD800 && c0 <= 0xDBFF) {
    return [FIRST_CHAR, 2]; // skip surrogate pair
  }

  // Map JavaScript Unicode code points to glyph indices
  // The C++ uses raw UTF-8 byte pairs; here we work directly with JS char codes.
  if (c0 < 0x80) {
    // ASCII
    return [c0, 1];
  }

  // Multi-byte: inspect next char for the composed codepoint
  const c1 = pos + 1 < str.length ? str.charCodeAt(pos + 1) : 0;
  const codePoint = c0 <= 0xD7FF ? c0 : ((c0 & 0x3FF) << 10) | (c1 & 0x3FF);

  // Map common non-ASCII to extra glyph indices (mirrors mapUtf8PairToFontByte in OLED.h)
  // JS encodes these as single code points, so we match on the code point value.
  switch (codePoint) {
    case 0x00E4: return [128, 1]; // ä
    case 0x00F6: return [129, 1]; // ö
    case 0x00FC: return [130, 1]; // ü
    case 0x00C4: return [131, 1]; // Ä
    case 0x00D6: return [132, 1]; // Ö
    case 0x00DC: return [133, 1]; // Ü
    case 0x00DF: return [134, 1]; // ß
    case 0x00B0: return [135, 1]; // °
    default:     return [FIRST_CHAR, 1]; // unknown → space
  }
}

/**
 * Render text into a 128×64 flat pixel array (row-major, index = y*128+x).
 *
 * @param text   The string to render.
 * @param startY The top pixel row where drawing begins (0–63).
 * @param scale  1 = normal 6×8 glyphs; 2 = glyphs scaled to 12×16.
 * @param bitmap The target array (must be 128*64 entries, values 0|1).
 * @param maxY   Pixel row at which to stop drawing (exclusive). Defaults to 64.
 */
export function renderTextToBitmap(
  text: string,
  startY: number,
  scale: 1 | 2,
  bitmap: Array<0 | 1>,
  maxY = 64
): void {
  const glyphW = GLYPH_WIDTH * scale;
  let cursorX = 0;
  let cursorY = startY;

  let i = 0;
  while (i < text.length) {
    const ch = text[i];

    if (ch === '\n') {
      cursorX = 0;
      cursorY += GLYPH_HEIGHT * scale;
      i++;
      continue;
    }

    const [glyphIdx, consumed] = decodeUtf8Char(text, i);
    i += consumed;

    if (cursorX + glyphW > 128) {
      cursorX = 0;
      cursorY += GLYPH_HEIGHT * scale;
    }

    if (cursorY >= maxY) break;

    const glyph = glyphBytes(glyphIdx);

    for (let col = 0; col < GLYPH_WIDTH; col++) {
      const colByte = glyph[col];
      for (let row = 0; row < GLYPH_HEIGHT; row++) {
        const px = (colByte >> row) & 1;
        if (!px) continue;

        const px0x = cursorX + col * scale;
        const px0y = cursorY + row * scale;

        for (let sy = 0; sy < scale; sy++) {
          const py = px0y + sy;
          if (py < 0 || py >= maxY) continue;
          for (let sx = 0; sx < scale; sx++) {
            const px2 = px0x + sx;
            if (px2 < 0 || px2 >= 128) continue;
            bitmap[py * 128 + px2] = 1;
          }
        }
      }
    }

    cursorX += glyphW;
  }
}
